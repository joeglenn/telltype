package net.jbglenn.telltype.support

import android.content.res.AssetManager
import java.io.File
import java.io.IOException
import kotlin.time.Duration.Companion.milliseconds
import net.jbglenn.telltype.core.model.RecordingId
import net.jbglenn.telltype.core.model.SessionId
import net.jbglenn.telltype.core.model.audio.AudioClip
import net.jbglenn.telltype.core.model.audio.AudioFormat
import net.jbglenn.telltype.core.model.audio.SpeechPresence

/**
 * The Diagnostics self-test sample bundled in every build type (`assets/selftest/sample.wav`: 2.7 s, 16 kHz mono
 * 16-bit, a neutral synthetic sentence spoken by the offline voice the evaluation uses; generated by
 * `android/scripts/make-selftest-sample.py`). It is not test data and not anyone's dictation.
 */
internal object SelfTestSampleAsset {
    /** Asset path of the sample. */
    const val ASSET = "selftest/sample.wav"

    /** The sentence the sample speaks; the self-test expects it back after transcription and cleanup. */
    const val EXPECTED_TEXT = "This is a short test of the dictation service."

    /** Size of the canonical WAV header the generator writes. */
    const val WAV_HEADER_BYTES = 44L

    /**
     * Copies the sample to `<cacheDir>/selftest/sample.wav` (the engines take a file) and describes it as a clip of
     * [session]. Null when the asset cannot be read or the copy cannot be written. Call off the main thread.
     */
    fun copyTo(assets: AssetManager, cacheDir: File, session: SessionId): AudioClip? = try {
        val file = File(cacheDir, ASSET)
        file.parentFile?.mkdirs()
        assets.open(ASSET).use { input -> file.outputStream().use { input.copyTo(it) } }
        val format = AudioFormat.Dictation
        val bytesPerSecond = format.sampleRateHz * format.channelCount * format.bitsPerSample / BITS_PER_BYTE
        AudioClip(
            recording = RecordingId(SELF_TEST_ID),
            session = session,
            path = file.absolutePath,
            format = format,
            duration = ((file.length() - WAV_HEADER_BYTES) * MILLIS_PER_SECOND / bytesPerSecond).milliseconds,
            speech = SpeechPresence.CLEAR,
        )
    } catch (_: IOException) {
        null
    }

    private const val SELF_TEST_ID = "self-test"
    private const val BITS_PER_BYTE = 8
    private const val MILLIS_PER_SECOND = 1_000L
}
