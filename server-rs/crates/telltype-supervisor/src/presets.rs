//! The presets file for `llama-server --models-preset`: one section per model the server can run.
//!
//! Sections come from two places: every `*.gguf` in the configured model directories (named by the
//! lower-cased file name without `.gguf`; multimodal projectors and later shards of split files are
//! skipped; split files are named without the `-00001-of-0000N` suffix), each with the configured
//! default keys; and the sections of an existing `models.ini` (for example llama-router's), copied as
//! they are. A name in both keeps the `models.ini` section, which carries tuned settings.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

#[derive(Debug, thiserror::Error)]
pub enum PresetError {
    #[error("cannot read model directory {path}: {source}")]
    ReadDir { path: String, source: std::io::Error },
    #[error("cannot read {path}: {source}")]
    ReadIni { path: String, source: std::io::Error },
    #[error("cannot write {path}: {source}")]
    Write { path: String, source: std::io::Error },
    #[error("no models found (model_dirs and models_ini are both empty)")]
    Empty,
}

/// The generated file and the model names it defines, in order.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Presets {
    pub text: String,
    pub names: Vec<String>,
}

/// Build the presets text.
pub fn build_presets(
    model_dirs: &[PathBuf],
    models_ini: Option<&Path>,
    defaults: &BTreeMap<String, String>,
) -> Result<Presets, PresetError> {
    let ini = models_ini
        .map(|p| {
            std::fs::read_to_string(p).map_err(|source| PresetError::ReadIni {
                path: p.display().to_string(),
                source,
            })
        })
        .transpose()?
        .unwrap_or_default();
    let ini_names = section_names(&ini);
    let mut text = String::from("; Generated by telltype-server at start; edits are overwritten.\n");
    let mut names = Vec::new();
    for dir in model_dirs {
        for (name, path) in gguf_models(dir)? {
            if ini_names.contains(&name) || names.contains(&name) {
                continue;
            }
            let _ = write!(text, "\n[{name}]\nmodel = {}\n", path.display());
            for (key, value) in defaults {
                let _ = writeln!(text, "{key} = {value}");
            }
            names.push(name);
        }
    }
    if !ini.trim().is_empty() {
        text.push('\n');
        text.push_str(&ini);
        if !ini.ends_with('\n') {
            text.push('\n');
        }
        names.extend(ini_names.into_iter().filter(|n| n != "*"));
    }
    if names.is_empty() {
        return Err(PresetError::Empty);
    }
    Ok(Presets { text, names })
}

/// Write the presets atomically (temporary file in the same directory, then rename), mode 0600.
pub fn write_presets(path: &Path, presets: &Presets) -> Result<(), PresetError> {
    let write_error = |source| PresetError::Write {
        path: path.display().to_string(),
        source,
    };
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(write_error)?;
    }
    let temporary = path.with_extension("ini.tmp");
    {
        use std::io::Write;
        use std::os::unix::fs::OpenOptionsExt;
        let mut file = std::fs::OpenOptions::new()
            .write(true)
            .create(true)
            .truncate(true)
            .mode(0o600)
            .open(&temporary)
            .map_err(write_error)?;
        file.write_all(presets.text.as_bytes()).map_err(write_error)?;
    }
    std::fs::rename(&temporary, path).map_err(write_error)
}

fn gguf_models(dir: &Path) -> Result<Vec<(String, PathBuf)>, PresetError> {
    let read_error = |source| PresetError::ReadDir {
        path: dir.display().to_string(),
        source,
    };
    let mut found = Vec::new();
    for entry in std::fs::read_dir(dir).map_err(read_error)? {
        let path = entry.map_err(read_error)?.path();
        let Some(file) = path.file_name().and_then(|f| f.to_str()) else {
            continue;
        };
        let Some(stem) = file.strip_suffix(".gguf") else {
            continue;
        };
        let lower = stem.to_lowercase();
        if lower.contains("mmproj") || !path.is_file() {
            continue;
        }
        let name = match split_shard(&lower) {
            Some((base, 1)) => base.to_owned(),
            Some(_) => continue,
            None => lower,
        };
        found.push((name, path));
    }
    found.sort();
    Ok(found)
}

/// `name-00001-of-00003` -> `("name", 1)`.
fn split_shard(stem: &str) -> Option<(&str, u32)> {
    let (rest, total) = stem.rsplit_once("-of-")?;
    let (base, index) = rest.rsplit_once('-')?;
    if total.len() != 5 || index.len() != 5 || !total.bytes().all(|b| b.is_ascii_digit()) {
        return None;
    }
    Some((base, index.parse().ok()?))
}

fn section_names(ini: &str) -> Vec<String> {
    ini.lines()
        .filter_map(|line| {
            line.trim()
                .strip_prefix('[')?
                .strip_suffix(']')
                .map(|n| n.trim().to_owned())
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeMap;
    use std::os::unix::fs::PermissionsExt;
    use std::path::PathBuf;

    use super::{PresetError, build_presets, split_shard, write_presets};

    fn scratch(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("telltype-presets-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    fn models_from_directories_and_ini_with_defaults() {
        let dir = scratch("build");
        for file in [
            "Qwen_Qwen3.5-4B-Q4_K_M.gguf",
            "gemma-4-E4B_q4_0-it.gguf",
            "mmproj-F16.gguf",
            "Big-00001-of-00002.gguf",
            "Big-00002-of-00002.gguf",
            "notes.txt",
            "dup.gguf",
        ] {
            std::fs::write(dir.join(file), b"x").unwrap();
        }
        let ini = dir.join("models.ini");
        std::fs::write(
            &ini,
            "[dup]\nmodel = /elsewhere/dup.gguf\nctx-size = 4096\n\n[nemotron]\nmodel = /n.gguf",
        )
        .unwrap();
        let defaults = BTreeMap::from([
            ("ctx-size".to_owned(), "8192".to_owned()),
            ("n-gpu-layers".to_owned(), "999".to_owned()),
        ]);
        let presets = build_presets(std::slice::from_ref(&dir), Some(&ini), &defaults).unwrap();
        assert_eq!(
            presets.names,
            [
                "big",
                "gemma-4-e4b_q4_0-it",
                "qwen_qwen3.5-4b-q4_k_m",
                "dup",
                "nemotron"
            ]
        );
        let big = format!(
            "[big]\nmodel = {}\nctx-size = 8192\nn-gpu-layers = 999\n",
            dir.join("Big-00001-of-00002.gguf").display()
        );
        assert!(presets.text.contains(&big), "{}", presets.text);
        assert!(
            presets.text.contains("[dup]\nmodel = /elsewhere/dup.gguf"),
            "models.ini wins"
        );
        assert_eq!(presets.text.matches("[dup]").count(), 1);
        assert!(presets.text.ends_with("model = /n.gguf\n"));
        let out = dir.join("state/presets.ini");
        write_presets(&out, &presets).unwrap();
        assert_eq!(std::fs::read_to_string(&out).unwrap(), presets.text);
        assert_eq!(
            std::fs::metadata(&out).unwrap().permissions().mode() & 0o777,
            0o600
        );
        std::fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn errors_are_typed() {
        let missing = PathBuf::from("/nonexistent/models");
        assert!(matches!(
            build_presets(std::slice::from_ref(&missing), None, &BTreeMap::new()),
            Err(PresetError::ReadDir { .. })
        ));
        assert!(matches!(
            build_presets(&[], Some(&missing), &BTreeMap::new()),
            Err(PresetError::ReadIni { .. })
        ));
        let empty = scratch("empty");
        assert!(matches!(
            build_presets(std::slice::from_ref(&empty), None, &BTreeMap::new()),
            Err(PresetError::Empty)
        ));
        let presets = super::Presets {
            text: String::new(),
            names: vec![],
        };
        assert!(matches!(
            write_presets(&PathBuf::from("/proc/telltype/x.ini"), &presets),
            Err(PresetError::Write { .. })
        ));
        std::fs::remove_dir_all(&empty).unwrap();
    }

    #[test]
    fn shard_names() {
        assert_eq!(split_shard("m-00001-of-00003"), Some(("m", 1)));
        assert_eq!(split_shard("m-00002-of-00003"), Some(("m", 2)));
        assert_eq!(split_shard("plain"), None);
        assert_eq!(split_shard("a-1-of-2"), None);
    }
}
